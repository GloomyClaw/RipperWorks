    public LocalizationService(string language)
    {
        CurrentLanguage = SupportedLanguages.IsSupported(language)
            ? language
            : SupportedLanguages.Russian;
    }

    public event EventHandler? LanguageChanged;

    public string CurrentLanguage { get; private set; }

    public string Get(string key)
    {
        var dictionary = CurrentLanguage == SupportedLanguages.English
            ? English
            : Russian;
        return dictionary.TryGetValue(key, out var value) ? value : key;
    }

    public string Format(string key, params object[] args) =>
        string.Format(Get(key), args);

    public void SetLanguage(string language)
    {
        var normalized = SupportedLanguages.IsSupported(language)
            ? language
            : SupportedLanguages.Russian;
        if (CurrentLanguage == normalized)
            return;
        CurrentLanguage = normalized;
        LanguageChanged?.Invoke(this, EventArgs.Empty);
    }
